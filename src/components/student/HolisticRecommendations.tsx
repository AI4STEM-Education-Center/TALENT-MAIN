import { Check, Loader2, Sparkles } from "lucide-react";
import { RecommendationCard } from "@/components/student/RecommendationCard";
import { AiMetricsLine } from "@/components/ai-metrics-line";
import {
  RESULT_STATUS,
  isResultPending,
  type ResultComponentMetrics,
  type ResultStatus,
  type PresignedRecommendation,
} from "@/lib/exam-results";
import type { ResourceSurface } from "@/lib/resource-telemetry";
import { recommendationKey } from "./recommendation-key";

/**
 * Study-material recommendations shared by student results and the authorized
 * teacher attempt view: up to 3 holistic cards chosen across the whole attempt.
 * Deliberately carries NO per-question framing — it never says which questions
 * were wrong, only what to study next.
 */
export function HolisticRecommendations({
  recommendations,
  status,
  metrics,
  audience = "student",
  attemptId,
  telemetrySurface,
  onOpen,
  viewedKeys,
  showHeading = true,
}: {
  recommendations: PresignedRecommendation[];
  status: ResultStatus;
  metrics: ResultComponentMetrics | null;
  audience?: "student" | "teacher";
  /**
   * The attempt that produced these recommendations. Its presence turns on the
   * rating control, on BOTH surfaces — the student rates their own study
   * material, and the teacher rates the same cards from the student's stats
   * page. A verdict is always tied to the attempt that surfaced the card, so
   * "was this a good recommendation" is answerable (see /api/feedback).
   */
  attemptId?: string;
  /**
   * Set only on the student's own results: records each open of a card's
   * pages as a LearningResourceSession labelled with this surface.
   */
  telemetrySurface?: ResourceSurface;
  /** Called with a card's recommendationKey each time it is opened. */
  onOpen?: (key: string) => void;
  /** recommendationKeys to mark as already viewed. */
  viewedKeys?: ReadonlySet<string>;
  /** The section heading; off when a page already introduces it. */
  showHeading?: boolean;
}) {
  const pending = isResultPending(status);

  return (
    /* Container for the card grid below: column count must follow the
       available width, not the viewport — beside the simulation rail this
       section gets only part of the page, and the cards must stack instead
       of splitting into slivers. */
    <div className="space-y-3 @container">
      {showHeading && (
        <h2 className="flex items-center gap-1.5 text-lg font-semibold">
          <Sparkles className="size-5 text-primary" /> Study recommendations
        </h2>
      )}

      {recommendations.length > 0 ? (
        <div className="grid gap-3 @lg:grid-cols-2 @3xl:grid-cols-3">
          {recommendations.map((rec) => {
            const key = recommendationKey(rec);
            return (
              <div key={key} className="relative">
                <RecommendationCard
                  rec={rec}
                  attemptId={attemptId}
                  audience={audience}
                  telemetrySurface={
                    audience === "student" ? telemetrySurface : undefined
                  }
                  onOpen={onOpen ? () => onOpen(key) : undefined}
                />
                {viewedKeys?.has(key) && (
                  <span className="pointer-events-none absolute right-3 top-3 inline-flex items-center gap-1 rounded-full bg-green-600/10 px-2 py-0.5 text-[11px] font-semibold text-green-700 backdrop-blur-sm dark:text-green-400">
                    <Check className="size-3" aria-hidden /> Viewed
                  </span>
                )}
              </div>
            );
          })}
        </div>
      ) : pending ? (
        <div className="flex items-center gap-2 rounded-xl border p-4 text-sm text-muted-foreground">
          <Loader2 className="size-4 animate-spin text-primary" /> Finding study
          material
          {audience === "student" ? " for you" : " for this student"}…
        </div>
      ) : status === RESULT_STATUS.FAILED ? (
        <div className="rounded-xl border p-4 text-sm text-muted-foreground">
          We couldn&apos;t generate study recommendations for this attempt.
          Please try again later.
        </div>
      ) : (
        <div className="rounded-xl border border-dashed p-4 text-sm text-muted-foreground">
          No specific study material to recommend right now — review your class
          materials to keep building on what you know.
        </div>
      )}

      {status === RESULT_STATUS.READY && metrics && (
        <AiMetricsLine
          metrics={metrics}
          prefix="Generated by "
          className="text-xs text-muted-foreground"
        />
      )}
    </div>
  );
}
