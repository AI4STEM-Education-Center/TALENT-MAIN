"use client";

import ReactMarkdown from "react-markdown";
import remarkGfm from "remark-gfm";
import { Loader2, Sparkles } from "lucide-react";
import { AiMetricsLine } from "@/components/ai-metrics-line";
import {
  RESULT_STATUS,
  type ResultComponentMetrics,
  type ResultStatus,
} from "@/lib/exam-results";

const MARKDOWN_CLASS =
  "text-sm [&_p]:mb-2 [&_p:last-child]:mb-0 [&_h3]:mb-1 [&_h3]:mt-3 [&_h3]:font-semibold [&_ul]:mb-2 [&_ul]:list-disc [&_ul]:pl-5 [&_ol]:mb-2 [&_ol]:list-decimal [&_ol]:pl-5 [&_li]:mb-1 [&_strong]:font-semibold";

const isPending = (status: ResultStatus) =>
  status === RESULT_STATUS.PENDING || status === RESULT_STATUS.GENERATING;

/** AI-generated attempt summary shared by the student and teacher result views. */
export function ResultSummary({
  summary,
  status,
  metrics,
}: {
  summary: string | null;
  status: ResultStatus;
  metrics: ResultComponentMetrics | null;
}) {
  return (
    <div className="space-y-2">
      <h2 className="flex items-center gap-1.5 text-base font-semibold">
        <Sparkles className="size-5 text-primary" /> Summary &amp; next steps
      </h2>
      {summary ? (
        <>
          <div className={MARKDOWN_CLASS} aria-live="polite">
            <ReactMarkdown remarkPlugins={[remarkGfm]}>{summary}</ReactMarkdown>
          </div>
          {isPending(status) && (
            <div className="flex items-center gap-2 text-xs text-muted-foreground">
              <Loader2 className="size-3.5 animate-spin text-primary" /> Writing the summary…
            </div>
          )}
          {status === RESULT_STATUS.READY && metrics && (
            <AiMetricsLine
              metrics={metrics}
              prefix="Generated by "
              className="text-xs text-muted-foreground"
            />
          )}
        </>
      ) : status === RESULT_STATUS.FAILED ? (
        <p className="text-sm text-muted-foreground">
          We couldn&apos;t generate a summary for this attempt.
        </p>
      ) : (
        <div className="flex items-center gap-2 text-sm text-muted-foreground">
          <Loader2 className="size-4 animate-spin text-primary" /> Generating the summary…
        </div>
      )}
    </div>
  );
}
