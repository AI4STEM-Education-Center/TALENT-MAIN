#!/usr/bin/env bash
#
# Tier 1 — one command, whole run, on the local production Docker image.
#
#   benchmark/run-local.sh                        # regression run + baseline diff
#   benchmark/run-local.sh --scenario smoke       # 30-second wiring check
#   benchmark/run-local.sh --update-baseline      # promote a passing run
#
# Mirrors what benchmark/ec2/provision.sh does on a clone: build, seed a golden
# database, start the stack, mint sessions, sample metrics, run k6, summarise,
# compare against the committed baseline. Same steps in the same order, so a
# finding here is reproducible there.
#
# What this tier can and cannot tell you: it detects regressions between commits,
# because the delta is measured on one machine with one dataset. It says nothing
# about capacity — a dev machine has more cores than the EC2 host and an NVMe
# fsync profile EBS cannot match. For capacity, breaking point, recovery and
# queue behaviour, use tier 3.

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BENCH_DIR="$REPO_ROOT/benchmark"
COMPOSE_FILE="$BENCH_DIR/docker/docker-compose.bench.yml"
ENV_FILE="$BENCH_DIR/docker/bench.env"
DATA_DIR="$BENCH_DIR/docker/data"
DB_FILE="$DATA_DIR/bench.db"
BASE_URL="http://localhost:3100"

SCENARIO="regression"
SCALE="${BENCH_SCALE:-0.25}"
SKIP_BUILD=false
SKIP_SEED=false
KEEP_UP=false
UPDATE_BASELINE=false
RUN_ID="local-$(date -u +%Y%m%d-%H%M%S)"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --scenario) SCENARIO="$2"; shift 2 ;;
    --scale) SCALE="$2"; shift 2 ;;
    --skip-build) SKIP_BUILD=true; shift ;;
    --skip-seed) SKIP_SEED=true; shift ;;
    --keep-up) KEEP_UP=true; shift ;;
    --update-baseline) UPDATE_BASELINE=true; shift ;;
    -h|--help) sed -n '2,20p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "unknown flag: $1" >&2; exit 2 ;;
  esac
done

RESULTS_DIR="$BENCH_DIR/results/$RUN_ID"
BASELINE="$BENCH_DIR/baseline/local-$SCENARIO.json"

log() { printf '\n\033[1m▸ %s\033[0m\n' "$*"; }
info() { printf '  %s\n' "$*"; }
die() { printf '\n\033[31m✗ %s\033[0m\n' "$*" >&2; exit 1; }

compose() { docker compose --env-file "$ENV_FILE" -f "$COMPOSE_FILE" "$@"; }

# ─── Preflight ───────────────────────────────────────────────────────────────

log "Preflight"
command -v docker >/dev/null 2>&1 || die "docker is required"
docker info >/dev/null 2>&1 || die "docker daemon is not running"
command -v k6 >/dev/null 2>&1 ||
  die "k6 is required — 'brew install k6', or benchmark/tools/install-k6.sh on Linux"
[[ -f "$BENCH_DIR/k6/scenarios/$SCENARIO.js" ]] || die "no scenario '$SCENARIO'"

# Secrets are generated on first run rather than committed. bench.env is
# gitignored, so a benchmark database can never be decrypted with a key that
# exists anywhere else.
if [[ ! -f "$ENV_FILE" ]]; then
  info "generating $ENV_FILE"
  cat >"$ENV_FILE" <<EOF
# Generated by benchmark/run-local.sh — gitignored, safe to delete.
BENCH_AUTH_SECRET=$(openssl rand -hex 32)
BENCH_API_KEY_ENCRYPTION_SECRET=$(openssl rand -hex 32)
EOF
fi
# shellcheck disable=SC1090
set -a; . "$ENV_FILE"; set +a

mkdir -p "$RESULTS_DIR" "$DATA_DIR" "$BENCH_DIR/baseline"

cleanup() {
  local code=$?
  set +e
  "$BENCH_DIR/collect/metrics.sh" stop --out "$RESULTS_DIR" >/dev/null 2>&1
  if [[ "$KEEP_UP" == true ]]; then
    log "--keep-up: stack left running at $BASE_URL"
    info "stop it with: docker compose --env-file $ENV_FILE -f $COMPOSE_FILE down -v"
  else
    log "Stopping the stack"
    compose logs --no-color --tail 2000 >"$RESULTS_DIR/container-logs.txt" 2>&1
    compose down --remove-orphans >/dev/null 2>&1
  fi
  exit $code
}
trap cleanup EXIT INT TERM

# ─── Build ───────────────────────────────────────────────────────────────────

log "Bundling the mock AI provider"
# The runtime image has no tsx, so the stub ships as plain JS. Same treatment as
# the EC2 path, so both tiers exercise identical mock behaviour.
mkdir -p "$BENCH_DIR/mock-ai/dist"
(cd "$REPO_ROOT" && npx esbuild benchmark/mock-ai/server.ts \
  --bundle --platform=node --target=node20 \
  --outfile=benchmark/mock-ai/dist/server.js --log-level=warning) || die "mock-ai bundle failed"

if [[ "$SKIP_BUILD" == false ]]; then
  log "Building the production image"
  # The same docker/Dockerfile production deploys use — measuring `next dev`
  # would measure the dev server's on-demand compilation, not the app.
  compose build bench-web || die "image build failed"
fi

# ─── Seed ────────────────────────────────────────────────────────────────────

if [[ "$SKIP_SEED" == false ]]; then
  log "Seeding the golden dataset (scale $SCALE)"
  rm -f "$DB_FILE" "$DB_FILE-wal" "$DB_FILE-shm"
  (
    cd "$REPO_ROOT"
    DATABASE_URL="file:$DB_FILE" npx prisma db push --accept-data-loss --skip-generate >/dev/null
    DATABASE_URL="file:$DB_FILE" BENCH_SCALE="$SCALE" \
      BENCH_MOCK_AI_URL="http://bench-mock-ai:8088/v1" \
      BENCH_MANIFEST_DIR="$RESULTS_DIR" npx tsx benchmark/seed/seed-bench.ts
  ) || die "seeding failed"
  # The container runs as uid 1001 and creates the -wal/-shm siblings itself.
  chmod 777 "$DATA_DIR"; chmod 666 "$DB_FILE"
else
  [[ -f "$DB_FILE" ]] || die "--skip-seed given but $DB_FILE does not exist"
  [[ -f "$RESULTS_DIR/dataset.json" ]] || cp "$BENCH_DIR/results/dataset.json" "$RESULTS_DIR/" 2>/dev/null ||
    die "--skip-seed needs a dataset manifest; run once without it first"
fi

# ─── Start ───────────────────────────────────────────────────────────────────

log "Starting the stack"
compose up -d --wait || die "stack did not become healthy — see: compose logs"
info "web at $BASE_URL, probe at http://127.0.0.1:9464"

log "Warm-up"
# Discarded on purpose. Next compiles routes lazily on first hit, SQLite's page
# cache is cold and mmap unwarmed; folding that into a comparison would measure
# start-up rather than the commit.
for path in /login /api/auth/csrf; do
  curl -fsS -o /dev/null "$BASE_URL$path" || true
done
sleep 5
# Reset the histogram so warm-up stalls stay out of the steady-state percentiles.
curl -fsS -o /dev/null "http://127.0.0.1:9464/reset" || info "probe not reachable — no in-process metrics"

log "Minting sessions"
(cd "$REPO_ROOT" && BENCH_SESSION_STUDENTS=40 BENCH_SESSION_TEACHERS=3 \
  npx tsx benchmark/tools/mint-sessions.ts \
    --url "$BASE_URL" --manifest "$RESULTS_DIR/dataset.json" \
    --out "$RESULTS_DIR/sessions.json" --spread-ip=true) || die "session minting failed"

# ─── Run ─────────────────────────────────────────────────────────────────────

log "Collecting host metrics"
"$BENCH_DIR/collect/metrics.sh" start --out "$RESULTS_DIR" --interval 5 \
  --queue-db "$DATA_DIR/bench-queue.db" || info "metrics collection unavailable"

log "Running scenario: $SCENARIO"
set +e
# --summary-trend-stats is not optional: k6's default trend set omits p(99) and
# count, and the reporter needs both (a p95 without its sample count cannot be
# judged for significance by compare.ts).
k6 run \
  --env "BENCH_TIER=local" \
  --env "BENCH_BASE_URL=$BASE_URL" \
  --env "BENCH_PROBE_URL=http://127.0.0.1:9464" \
  --env "BENCH_RESULTS_DIR=$RESULTS_DIR" \
  --summary-trend-stats="avg,min,med,max,p(90),p(95),p(99),count" \
  --summary-export="$RESULTS_DIR/k6-summary.json" \
  "$BENCH_DIR/k6/scenarios/$SCENARIO.js" 2>&1 | tee "$RESULTS_DIR/k6.log"
K6_EXIT=${PIPESTATUS[0]}
set -e
info "k6 exited with $K6_EXIT"

"$BENCH_DIR/collect/metrics.sh" stop --out "$RESULTS_DIR" >/dev/null 2>&1 || true

# ─── Report ──────────────────────────────────────────────────────────────────

log "Summarising"
(cd "$REPO_ROOT" && npx tsx benchmark/collect/summarize.ts \
  --run "$RESULTS_DIR" --tier local --label "$SCENARIO@$(git rev-parse --short HEAD)") ||
  die "summarize failed"

COMPARE_EXIT=0
if [[ -f "$BASELINE" ]]; then
  log "Comparing against the baseline"
  set +e
  (cd "$REPO_ROOT" && npx tsx benchmark/collect/compare.ts \
    --baseline "$BASELINE" --candidate "$RESULTS_DIR/summary.json" \
    ${UPDATE_BASELINE:+--update-baseline})
  COMPARE_EXIT=$?
  set -e
else
  log "No baseline yet"
  info "establish one with: cp $RESULTS_DIR/summary.json $BASELINE"
  if [[ "$UPDATE_BASELINE" == true ]]; then
    cp "$RESULTS_DIR/summary.json" "$BASELINE"
    info "baseline created at $BASELINE"
  fi
fi

log "Done"
info "results : $RESULTS_DIR"
info "summary : $RESULTS_DIR/summary.md"

# k6's exit code (a breached threshold) takes precedence over the comparison's:
# an absolute SLO failure is a stronger statement than a relative regression.
if [[ "$K6_EXIT" != 0 ]]; then exit "$K6_EXIT"; fi
exit "$COMPARE_EXIT"
